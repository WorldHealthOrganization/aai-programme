/**
 * Create or update a set of programme issues from a spec file, with their
 * labels (the field values, `fields.ts`), sub-issues and "blocked by" links.
 *
 *   bun run scripts/programme/create-items.ts --spec scripts/programme/bean-intake.json --dry-run
 *   bun run scripts/programme/create-items.ts --spec scripts/programme/bean-intake.json
 *
 * Safe to rerun (AUTO-08): an item is matched by its title within the spec's
 * `marker` label, a missing label or link is added, and a body that differs
 * is updated. Only this repository's issues are touched.
 */
import { readFileSync } from "node:fs";
import { FIELDS, labelFor } from "./fields.ts";

interface Item { key: string; title: string; labels: string[]; fields: Record<string, string>; body: string; parent?: string; blockedBy?: string[] }
const at = process.argv.indexOf("--spec");
if (at < 0) {
  console.error("usage: create-items.ts --spec <file.json> [--dry-run]");
  process.exit(2);
}
const spec = JSON.parse(readFileSync(process.argv[at + 1]!, "utf8")) as { marker: string; repository?: string; items: Item[] };
const REPO = spec.repository ?? "litlfred/aai-programme";
const DRY = process.argv.includes("--dry-run");

function gh(args: string[], input?: string): unknown {
  const r = Bun.spawnSync(["gh", "api", ...args], { stdin: input ? new TextEncoder().encode(input) : undefined, stderr: "pipe" });
  if (r.exitCode !== 0) throw new Error(`gh api ${args.join(" ")}: ${new TextDecoder().decode(r.stderr).trim()}`);
  const out = new TextDecoder().decode(r.stdout).trim();
  return out ? JSON.parse(out) : undefined;
}
const labelsOf = (i: Item) => [spec.marker, ...i.labels, ...Object.entries(i.fields).filter(([f]) => f in FIELDS).map(([f, v]) => labelFor(f, v))];
const bodyOf = (i: Item) =>
  `${i.body}\n\n**Programme fields** (the labels hold the values the automations keep; the dates and the rest are read from here):\n\n| Field | Value |\n|---|---|\n${Object.entries(i.fields).map(([k, v]) => `| ${k} | ${v} |`).join("\n")}\n`;
/** A body written through an agent session can carry an attribution footer; it is not part of the item. */
const stored = (b: string | null | undefined) => (b ?? "").replace(/\n+---\n_Generated by \[Claude Code\]\([^)]*\)_\s*$/, "").trim();

type Issue = { number: number; id: number; title: string; body?: string | null; labels?: { name: string }[] };
const existing = new Map<string, Issue>();
try {
  for (const i of gh(["--paginate", `repos/${REPO}/issues?state=all&labels=${encodeURIComponent(spec.marker)}&per_page=100`]) as Issue[]) existing.set(i.title, i);
} catch (e) {
  if (!DRY) throw e;
}
const byKey = new Map<string, Issue>();
for (const item of spec.items) {
  const found = existing.get(item.title);
  if (!found) {
    if (DRY) console.log(`create  ${item.title}`);
    else {
      const made = gh(["-X", "POST", `repos/${REPO}/issues`, "--input", "-"], JSON.stringify({ title: item.title, body: bodyOf(item), labels: labelsOf(item) })) as Issue;
      byKey.set(item.key, made);
      console.log(`created #${made.number} ${item.title}`);
    }
    continue;
  }
  byKey.set(item.key, found);
  if (stored(found.body) !== bodyOf(item).trim()) {
    if (DRY) console.log(`body    #${found.number}`);
    else gh(["-X", "PATCH", `repos/${REPO}/issues/${found.number}`, "--input", "-"], JSON.stringify({ body: bodyOf(item) }));
  }
  const have = new Set((found.labels ?? []).map((l) => l.name));
  const missing = labelsOf(item).filter((l) => !have.has(l));
  if (missing.length) {
    if (DRY) console.log(`label   #${found.number} + ${missing.join(", ")}`);
    else gh(["-X", "POST", `repos/${REPO}/issues/${found.number}/labels`, "--input", "-"], JSON.stringify({ labels: missing }));
  }
}
for (const item of spec.items) {
  const me = byKey.get(item.key);
  const links: [string, string][] = [...(item.parent ? [["parent", item.parent] as [string, string]] : []), ...(item.blockedBy ?? []).map((b) => ["blocked", b] as [string, string])];
  for (const [kind, other] of links) {
    const them = byKey.get(other);
    if (!me || !them) {
      console.log(`link    ${item.key} ${kind} ${other}`);
      continue;
    }
    if (DRY) continue;
    if (kind === "parent") {
      const subs = gh([`repos/${REPO}/issues/${them.number}/sub_issues?per_page=100`]) as Issue[];
      if (!subs.some((s) => s.id === me.id)) gh(["-X", "POST", `repos/${REPO}/issues/${them.number}/sub_issues`, "-F", `sub_issue_id=${me.id}`]);
    } else {
      const deps = gh([`repos/${REPO}/issues/${me.number}/dependencies/blocked_by`]) as Issue[];
      if (!deps.some((d) => d.id === them.id)) gh(["-X", "POST", `repos/${REPO}/issues/${me.number}/dependencies/blocked_by`, "-F", `issue_id=${them.id}`]);
    }
  }
}
console.log(DRY ? "dry run: nothing changed" : `${spec.items.length} item(s) in step`);
